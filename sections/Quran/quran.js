function normalizeType(type) {
  const t = String(type).toLowerCase();

  if (t === "pdf") return "pdf";

  if (t === "mp3" || t === "audio") {
    return "audio";
  }

  if (t === "mp4" || t === "video") {
    return "video";
  }

  if (t === "jpg" || t === "jpeg" || t === "png" || t === "image") {
    return "image";
  }

  if (t === "exam") {
    return "exam";
  }

  if (t === "book") {
    return "book";
  }

  return t;
}

function getFilterLabel(type) {
  const labels = {
    all: "✨ الكل",
    pdf: "📄 PDF",
    image: "🖼 صور",
    video: "🎥 فيديوهات",
    audio: "🎵 صوت",
    exam: "📝 اختبار",
    book: "📚 كتب",
    lesson: "📖 دروس التجويد",
    plan: "📋 خطط الحفظ",
  };

  return labels[type] || type;
}

function createFilters(section, renderCallback) {
  filterBar.innerHTML = "";

  const types = [
    ...new Set(
      section.lessons.map(function (lesson) {
        return normalizeType(lesson.fileType);
      }),
    ),
  ];

  const filters = ["all", ...types];

  filters.forEach(function (type) {
    const btn = document.createElement("button");

    btn.className = "filter-btn" + (type === "all" ? " active" : "");

    btn.textContent = getFilterLabel(type);

    btn.addEventListener("click", function () {
      document.querySelectorAll(".filter-btn").forEach(function (b) {
        b.classList.remove("active");
      });

      btn.classList.add("active");

      currentFilter = type;

      renderCallback();
    });

    filterBar.appendChild(btn);
  });
}

